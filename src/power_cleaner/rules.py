SAFETY_DESCRIPTIONS: dict[SafetyLevel, str] = {
    SafetyLevel.SAFE: (
        "Chrome can regenerate this data on demand. "
        "Deleting it reclaims space without removing personal browser data."
    ),
    SafetyLevel.LOW_RISK: (
        "Usually safe to remove, but may cause Chrome to redownload data "
        "or recreate component/extension resources."
    ),
    SafetyLevel.REVIEW: (
        "May contain persistent website or application state. "
        "Inspect carefully before deciding to delete."
    ),
    SafetyLevel.PROTECTED: (
        "Important user or browser state. Never automatically cleaned."
    ),
    SafetyLevel.UNKNOWN: ("Not recognized by the current rules database."),
    SafetyLevel.INACCESSIBLE: (
        "Could not be inspected safely (permissions or disappearing file)."
    ),
}

