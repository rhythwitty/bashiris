class RuleRegistry:
    """Registry of rules with efficient prefix matching for relative paths."""

    def __init__(self, rules: list[Rule] | None = None) -> None:
        self._rules: dict[str, Rule] = {}
        for rule in rules or DEFAULT_RULES:
            self.register(rule)

    def register(self, rule: Rule) -> None:
        norm = rule.normalized_path
        self._rules[norm] = rule

    def get_rule(self, normalized_path: str) -> Rule | None:
        return self._rules.get(normalized_path)

    def all_rules(self) -> list[Rule]:
        return list(self._rules.values())

    def match_path(self, relative_path: str) -> Rule | None:
        """Find the most specific rule matching the given relative path.

        Rules match:
        1. Exact match on normalized path.
        2. Directory prefix match (longest prefix wins).
        3. Sidecar files for SQLite databases (e.g. -wal, -journal, -shm).
        """
        norm = relative_path.replace("\\", "/").strip("/")

        # 1. Exact match
        if norm in self._rules:
            return self._rules[norm]

        # 2. SQLite sidecar matches (e.g. "Default/History-wal" -> "Default/History")
        for suffix in ("-wal", "-journal", "-shm"):
            if norm.endswith(suffix):
                base = norm[: -len(suffix)]
                if base in self._rules:
                    return self._rules[base]

        # 3. Directory ancestor matching: longest matching prefix wins
        parts = norm.split("/")
        # Check from longest prefix down to shortest
        for i in range(len(parts) - 1, 0, -1):
            prefix = "/".join(parts[:i])
            if prefix in self._rules:
                return self._rules[prefix]

        return None
